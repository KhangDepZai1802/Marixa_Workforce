const textCache = new WeakMap();
const attrCache = new WeakMap();

const translateDocument = (language) => {
    const update = (root = document.body) => {
        const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
        let node;
        while ((node = walker.nextNode())) {
            const current = node.nodeValue;
            const previous = textCache.get(node);
            const source = previous && previous.output === current ? previous.source : current;
            const output = translate(source, language);
            textCache.set(node, { source, output });
            if (output !== current) node.nodeValue = output;
        }
        const attrElements = [
            ...(root.matches?.("[placeholder], [title], [aria-label]") ? [root] : []),
            ...(root.querySelectorAll?.("[placeholder], [title], [aria-label]") || []),
        ];
        attrElements.forEach((element) => {
            let cache = attrCache.get(element);
            if (!cache) { cache = {}; attrCache.set(element, cache); }
            ["placeholder", "title", "aria-label"].forEach((attribute) => {
                if (!element.hasAttribute(attribute)) return;
                const current = element.getAttribute(attribute);
                const previous = cache[attribute];
                const source = previous && previous.output === current ? previous.source : current;
                const output = translate(source, language);
                cache[attribute] = { source, output };
                if (output !== current) element.setAttribute(attribute, output);
            });
        });
    };
    update();
    const observer = new MutationObserver((changes) => changes.forEach((change) => {
        if (change.type === "childList") change.addedNodes.forEach((node) => {
            if (node.nodeType === Node.ELEMENT_NODE) update(node);
            else if (node.nodeType === Node.TEXT_NODE) {
                const output = translate(node.nodeValue, language);
                textCache.set(node, { source: node.nodeValue, output });
                if (output !== node.nodeValue) node.nodeValue = output;
            }
        });
        else if (change.type === "characterData") {
            const node = change.target;
            const current = node.nodeValue;
            const previous = textCache.get(node);
            const source = previous && previous.output === current ? previous.source : current;
            const output = translate(source, language);
            textCache.set(node, { source, output });
            if (output !== current) node.nodeValue = output;
        } else if (change.type === "attributes") update(change.target.parentElement || document.body);
    }));
    observer.observe(document.body, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ["placeholder", "title", "aria-label"] });
    return () => observer.disconnect();
};

export const LanguageProvider = ({ children }) => {
    const [language, setLanguageState] = useState(getLanguage);
    const setLanguage = (value) => {
        if (!["vi", "en", "zh"].includes(value)) return;
        try { localStorage.setItem(STORAGE_KEY, value); } catch { /* storage may be unavailable */ }
        setLanguageState(value);
    };
    useEffect(() => {
        document.documentElement.lang = language === "zh" ? "zh-CN" : language;
        return translateDocument(language);
    }, [language]);
    useEffect(() => {
        const onStorage = (event) => { if (event.key === STORAGE_KEY) setLanguageState(getLanguage()); };
        window.addEventListener("storage", onStorage);
        return () => window.removeEventListener("storage", onStorage);
    }, []);
    const value = useMemo(() => ({ language, setLanguage }), [language]);
    return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
};

export const useLanguage = () => useContext(LanguageContext) || { language: getLanguage(), setLanguage: () => {} };
